"""Generate docs/WEIGHTS.md: the justification for every tell weight, checked against data.

Run from the repo root:  python scripts/weights_report.py > docs/WEIGHTS.md
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import evalaware.layers  # noqa: E402,F401  (registers tells)
from evalaware import bench, calibrate, dataset, rationale  # noqa: E402
from evalaware.classify import classify  # noqa: E402
from evalaware.metrics import summarize  # noqa: E402
from evalaware.taxonomy import REGISTRY  # noqa: E402

measured = dataset.load_many(["data/measured"])
reference = dataset.load_many(["data/reference"])
groups = sorted({r["group"] for r in measured})
rows = calibrate.per_tell_stats(measured)
cv = calibrate.grouped_cv(measured)
agree = calibrate.rank_agreement(rows, "container")
abl = calibrate.tell_ablation(measured)
sweep = calibrate.threshold_sweep(measured)
perturb = [calibrate.perturbation(measured, s, draws=300) for s in (0.1, 0.25, 0.5, 1.0)]
summ = summarize([r["label"] for r in measured], [classify(dataset.fingerprint_of(r)).probs for r in measured])
miss_groups = sorted({r["group"] for r in measured if classify(dataset.fingerprint_of(r)).primary != r["label"]})
n_cont = sum(r["label"] == "container" for r in measured)

p = print
p("# Where the weights come from\n")
p("*Generated by `scripts/weights_report.py` — do not edit by hand.*\n")
p("The detector's weights are **not tuned numbers**. Each is determined by a fixed rubric, justified per tell, and then "
  "stress-tested against data. This page shows all three steps, including where the data disagrees with the priors.\n")

p("## 1. The rubric\n")
p("Every tell is placed in an evidence tier by two questions about the artefact it observes: *is it produced by the "
  "boundary or merely correlated with it?* and *how often does it appear in benign environments, and how hard is it "
  "to remove on purpose?* The tier fixes the weight band; `tests/test_rationale.py` fails if a weight leaves its band "
  "or a tell has no written rationale.\n")
p("| tier | band | meaning |\n|---|---|---|")
for t, (lo, hi), m in (("A", rationale.TIERS["A"], "produced by the boundary or its runtime; absent elsewhere; removal needs deliberate effort"),
                       ("B", rationale.TIERS["B"], "strong correlate set by runtime defaults; configurable, occasionally present elsewhere"),
                       ("C", rationale.TIERS["C"], "circumstantial: common under the boundary but also seen in benign setups"),
                       ("D", rationale.TIERS["D"], "weak heuristic: shows up on many ordinary machines")):
    p(f"| {t} | {lo:.2f}–{hi:.2f} | {m} |")
p("\n**Disclosure.** The numeric weights were written before this rubric. The rubric formalises the reasoning behind "
  "them and the test now keeps them consistent; it was not used to move any weight. Measurement did change "
  "the detector in two ways: `kn.image_residue` was set low after a Docker-built microVM image misled the container tells, "
  "and three host-side false positives were removed (see REPORT §3). The numbers on this page are therefore in-sample.\n")

p("### Why a noisy-OR\n")
p("Each tell is an independent-ish *reason to believe* a boundary exists, and each reason can fail on its own "
  "(it can be spoofed, or exist for a benign cause). Noisy-OR, `1 − Π(1 − wᵢ)`, models exactly that: any single reliable "
  "tell is enough, several weak ones add up, and no tell can push the score *down* (the absence of a tell is weak "
  "evidence, because tells are easy to remove). A max would ignore corroboration; naive Bayes needs a calibrated "
  "likelihood for every tell, which the data cannot supply (see §3). Its cost is the independence assumption: "
  "correlated tells (a Docker container shows seven container tells at once) make it overconfident at the top. "
  f"On the measured set the expected calibration error is {summ['ece']:.3f} and the Brier score {summ['brier']:.3f}; "
  "§5 lists the confident-but-wrong cases.\n")

p("### The weight of every tell\n")
p("| tell | layer | tier | weight | why it is evidence | what undermines it |\n|---|---|---|---|---|---|")
order = sorted(REGISTRY, key=lambda n: (rationale.tier_of(n), -max(REGISTRY[n].votes.values()), n))
for n in order:
    spec = REGISTRY[n]
    votes = ", ".join(f"{b} {w:.2f}" for b, w in spec.votes.items())
    tier, why, conf = rationale.RATIONALE[n]
    p(f"| `{n}` | {spec.layer} | {tier} | {votes} | {why} | {conf} |")

p("\n## 2. Do the data agree?\n")
p(f"Data: {len(measured)} measured records from {len(groups)} configurations ({n_cont} container, "
  f"{len(measured) - n_cont} non-container). Configurations, not records, are the unit of independence "
  "(repeats of one configuration are near-identical).\n")
p("### 2a. Per-tell rates, container boundary\n")
p("*Balanced precision* is P(container | tell fired) if containers and non-containers were equally common, "
  "so it is comparable to a weight regardless of how many container samples the dataset has "
  "(+0.5 smoothing). TPR/FPR are the fraction of container / non-container samples where the tell fired.\n")
p("| tell | tier | prior weight | balanced precision | TPR | FPR | fired (tp / fp) |\n|---|---|---|---|---|---|---|")
for r in sorted((r for r in rows if r["boundary"] == "container" and r["informative"] and r["tp"] + r["fp"] > 0),
                key=lambda r: -r["prior_weight"]):
    p(f"| `{r['tell']}` | {r['tier']} | {r['prior_weight']:.2f} | {r['balanced_precision']:.2f} | {r['tpr']:.2f} | "
      f"{r['fpr']:.2f} | {r['tp']} / {r['fp']} |")
p(f"\nSpearman rank correlation between prior weight and balanced precision over these {agree['n_tells']} tells: "
  f"**{agree['spearman']:.2f}**. The priors order the tells broadly the way the data does, but not tightly. Specific disagreements:\n")
by = {r["tell"]: r for r in rows if r["boundary"] == "container"}
d = by["ct.dockerenv"]
p(f"- `ct.dockerenv` (prior {d['prior_weight']:.2f}) shows balanced precision {d['balanced_precision']:.2f}: it fired in {d['fp']} "
  "non-container samples. These are the `chroot-export` configuration, a directory tree made with `docker export`, which "
  "carries the marker file into a chroot. Tier A's \"cannot exist without the boundary\" is too strong for this tell; the "
  "residue risk is written into its rationale, and the weight stays until there is evidence from more than one such case.")
lower = [(n, by[n]) for n in ("kn.overlay_root", "nt.hostname_random_hex", "kn.cgroup_container_path")]
p("- " + ", ".join(f"`{n}` (prior {r['prior_weight']:.2f} → data {r['balanced_precision']:.2f})" for n, r in lower) +
  " look stronger in the data than their priors. I did **not** raise them: every non-container sample here comes from one VM "
  "(plus chroots of one image), so the benign cases that would set these tells (live-CD overlay roots, randomly named hosts, "
  "odd cgroup layouts) never appear among the negatives. Zero false positives on that negative set is weak evidence.")
p("- `ct.pid1_not_init` and `hw.dmi_absent` fire in nearly every sample, container or not; their low weights are right, "
  "and `hw.dmi_absent`'s container vote is effectively uninformative (balanced precision ≈ 0.5).\n")
p("### 2b. Boundaries the data cannot test\n")
vm_rows = [r for r in rows if r["boundary"] == "vm"]
p(f"- **vm**: every measured sample runs on a VM host, so there are no non-VM negatives ({sum(not r['informative'] for r in vm_rows)} of "
  f"{len(vm_rows)} vm-vote tells are uninformative here). VM weights rest on the rubric alone and on the 12 hand-written fixtures, "
  "which are circular. A bare-metal sample is the single most valuable addition.")
p("- **userspace_kernel**: no measured gVisor/Kata sample. `kn.gvisor_banner` and `tm.slow_syscall` are untested.\n")

p("## 3. Does fitting beat the priors?\n")
p("A logistic regression for the container boundary (L2 = 1, one feature per container-voting tell) was trained and scored "
  f"with **leave-one-configuration-out** cross-validation over {cv['n_groups']} configurations "
  "(the vm and userspace_kernel scores keep their prior values, since the data cannot fit them).\n")
p("| model | 4-class accuracy | container Brier |\n|---|---|---|")
p(f"| hand-set prior weights (no training) | {cv['prior']['accuracy']:.3f} | {cv['prior']['container_brier']:.3f} |")
p(f"| logistic regression, grouped CV | {cv['fitted']['accuracy']:.3f} | {cv['fitted']['container_brier']:.3f} |")
better = cv["prior"]["accuracy"] >= cv["fitted"]["accuracy"]
p(f"\n{'The priors are at least as good as the fit' if better else 'The fit beats the priors'} "
  f"on held-out configurations ({n_cont} of {len(measured)} samples are containers and only {cv['n_groups']} configurations exist), "
  "so the weights are not replaced by fitted ones. With this little, highly correlated data the fit plausibly just memorises "
  "which configurations it saw. The decision rule going forward: switch to fitted weights only if they win under this same grouped CV on a "
  "dataset with independent negatives.\n")

p("## 4. Is the result fragile to the exact numbers?\n")
p(f"Baseline 4-class accuracy on the measured set: **{summ['accuracy']:.3f}**. Each weight was multiplied by `exp(σ·z)`, "
  "z ~ N(0,1), 300 random draws per σ (σ = 1 means weights routinely change by a factor of e). A perturbed weight replaces "
  "all of that tell's votes, which slightly overstates the perturbation for the two-vote tells:\n")
p("| σ | mean accuracy | 5th percentile | worst draw |\n|---|---|---|---|")
for q in perturb:
    p(f"| {q['sigma']} | {q['mean']:.3f} | {q['p05']:.3f} | {q['min']:.3f} |")
p("\nThe stack threshold (cut-off for listing a boundary in the isolation stack) swept 0.2–0.8:\n")
p("| threshold | exact stack match |\n|---|---|")
for s in sweep:
    p(f"| {s['threshold']:.1f} | {s['stack_exact']:.3f} |")
p("\nStack accuracy varies by a few points across thresholds. The default 0.5 was fixed before measurement and is not "
  "tuned to this table; the sweep shows the conclusion does not hinge on it.\n")
p("### Redundancy\n")
p(f"Zeroing any single tell (of {abl['n_tells']} that fire anywhere) changes accuracy by "
  f"{'no amount' if not abl['critical'] else 'up to ' + format(max(d for _, d in abl['critical']), '.3f')}: "
  "no one tell is load-bearing. Container samples show between "
  f"{abl['container_strong_tells_min']} and {abl['container_strong_tells_max']} container tells of weight ≥ 0.6; the zero is the "
  "bare namespace sandboxes (below).\n")

p("## 5. What the weights cannot fix\n")
p(f"Misclassified configurations: **{', '.join(miss_groups)}**. `unshare` sandboxes share the host's root filesystem and "
  "cgroups, so they carry no runtime artefact for any tell to find: no weight setting can detect what leaves no trace. "
  "`chroot-export` is the opposite error: one marker file imitates a container. These are properties of the evidence, "
  "not of the weights, which is why the sensitivity table is flat.\n")
p("## 6. To strengthen this\n")
p("1. A bare-metal laptop/server sample, to give the VM boundary real negatives.\n"
  "2. Several independent hosts per class, then re-run §3 on whole-host held-out folds.\n"
  "3. A gVisor/Kata sample to test the userspace_kernel tells.\n"
  "4. If grouped CV on that data favours fitted weights, replace the priors and keep the rubric as the regulariser.\n")
